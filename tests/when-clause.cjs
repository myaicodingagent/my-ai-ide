// The "when" clauses of extension menus (src/renderer/src/whenClause.ts). `npm run test:when`: does not start the app.
const fs = require('fs'), path = require('path')
const root = path.join(__dirname, '..')
const out = path.join(root, 'node_modules', '.cache', 'when-bundle.cjs')
fs.mkdirSync(path.dirname(out), { recursive: true })
require('esbuild').buildSync({ entryPoints: [path.join(root, 'src/renderer/src/whenClause.ts')], bundle: true, platform: 'node', format: 'cjs', outfile: out, logLevel: 'error' })
const { evalWhen, menuOrder } = require(out)
const results = []
const t = (clause, ctx, want) => { const got = evalWhen(clause, ctx); results.push(got === want); console.log(`${got === want ? 'PASS' : 'FAIL'}  ${JSON.stringify(clause)} with ${JSON.stringify(ctx)} -> ${got} (wanted ${want})`) }
const c = { view: 'v.tree', viewItem: 'fruit', flag: true }
t('', c, true)
t('view == v.tree', c, true)
t('view == v.other', c, false)
t('view != v.other', c, true)
t("viewItem == 'fruit'", c, true)
t('viewItem == "veg"', c, false)
t('view == v.tree && viewItem == fruit', c, true)
t('view == v.tree && viewItem == veg', c, false)
t('viewItem == veg || viewItem == fruit', c, true)
t('!(viewItem == veg)', c, true)
t('!flag', c, false)
t('flag', c, true)
t('missing', c, false)
t('!missing', c, true)
t('viewItem =~ /^(fruit|veg)$/', c, true)
t('viewItem =~ /^VEG/i', c, false)
t('viewItem =~ /FRUIT/i', c, true)
t('view == v.tree && (viewItem == a || viewItem == fruit) && !missing', c, true)
t('a == b == c', c, false)
t('view ==', c, false)
t('(view == v.tree', c, false)
t('viewItem == \'unterminated', c, false)
t('true', {}, true)
t('false', {}, false)
t('viewItem == fruit', { viewItem: undefined }, false)
const o = (g) => JSON.stringify(menuOrder(g))
results.push(o('1_modify@3') === '{"name":"1_modify","order":3}' && o('navigation') === '{"name":"navigation","order":0}' && o('inline@-1') === '{"name":"inline","order":-1}')
console.log(results[results.length - 1] ? 'PASS  group names and @order' : 'FAIL  group names and @order')
const failed = results.filter((x) => !x).length
console.log(`\n${results.length - failed}/${results.length} checks passed`)
process.exit(failed ? 1 : 0)
